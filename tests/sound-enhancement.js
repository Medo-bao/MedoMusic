    async function signal(settings, frequency, compare=false, amplitude=.5, sampleRate=48000) {
      const context = new OfflineAudioContext(2, sampleRate, sampleRate);
      const buffer = context.createBuffer(2,sampleRate,sampleRate);
      for (let ch=0; ch<2; ch++) {
        const data=buffer.getChannelData(ch);
        for(let i=0;i<data.length;i++) data[i]=amplitude*Math.sin(2*Math.PI*frequency*i/sampleRate);
      }
      const source=context.createBufferSource(); source.buffer=buffer;
      await MedoSound.prepare(context);
      const engine=MedoSound.create(context,source,context.destination);
      engine.update(settings,compare,true); source.start();
      const rendered=await context.startRendering();
      const data=rendered.getChannelData(0).slice(Math.floor(sampleRate/4));
      let harmonicSin=0,harmonicCos=0;
      for(let i=0;i<data.length;i++) { harmonicSin+=data[i]*Math.sin(2*Math.PI*frequency*3*i/sampleRate); harmonicCos+=data[i]*Math.cos(2*Math.PI*frequency*3*i/sampleRate); }
      return {rms:Math.sqrt(data.reduce((sum,x)=>sum+x*x,0)/data.length),peak:Math.max(...data.map(Math.abs)),finite:data.every(Number.isFinite),third:2*Math.hypot(harmonicSin,harmonicCos)/data.length};
    }
