    const nativeMax=new FxSoundCore.Maximizer(48000),nativePair=new Float32Array(2);
    let nativeRoomEnergy=0;
    for(let i=0;i<48000;i++) {
      const sample=Math.fround(.5*Math.sin(2*Math.PI*1000*i/48000));
      nativeRoom.processStereo(sample,sample,nativePair);
      nativeMax.processStereo(nativePair[0],nativePair[1],1,nativePair);
      if(i>=12000)nativeRoomEnergy+=nativePair[0]*nativePair[0];
    }
    const nativeRoomRms=Math.sqrt(nativeRoomEnergy/36000);
